-- 27. Rank restaurants by revenue within each city.

 SELECT restaurants.city,restaurants.restaurant_name, SUM (order_items.item_price*order_items.quantity) as revenue, RANK() OVER (PARTITION BY restaurants.city ORDER BY SUM(order_items.item_price * order_items.quantity) DESC)FROM restaurants INNER JOIN orders ON  restaurants.restaurant_id=orders.restaurant_id INNER JOIN order_items ON order_items.order_id=orders.order_id GROUP BY restaurants.city,restaurants.restaurant_name;

-- 28. Find the Top 3 restaurants in each city.

 SELECT city,restaurant_name,revenue, revenue_rank FROM(SELECT restaurants.city,restaurants.restaurant_name, SUM (order_items.item_price*order_items.quantity) as revenue, RANK() OVER (PARTITION BY restaurants.city ORDER BY SUM(order_items.item_price * order_items.quantity) DESC) AS revenue_rank FROM restaurants INNER JOIN orders ON  restaurants.restaurant_id=orders.restaurant_id INNER JOIN order_items ON order_items.order_id=orders.order_id GROUP BY restaurants.city,restaurants.restaurant_name ) AS ranked_restaurants WHERE revenue_rank <=3 ORDER BY city,revenue_rank;

