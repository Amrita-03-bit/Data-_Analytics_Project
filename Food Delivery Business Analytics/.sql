-- 23. Find the cancellation rate for each restaurant.
SELECT restaurants.restaurant_name, COUNT(CASE WHEN orders.order_status = 'Cancelled' THEN 1 END) AS cancelled_orders, COUNT(*) AS total_orders,COUNT(CASE WHEN orders.order_status = 'Cancelled' THEN 1 END) * 100.0 / COUNT(*) AS cancellation_rate FROM  food_delivery_db.restaurants INNER JOIN food_delivery_db.orders ON restaurants.restaurant_id = orders.restaurant_id GROUP BY restaurants.restaurant_name;

-- 24. Identify restaurants with the highest cancellation rate.

SELECT restaurants.restaurant_name, COUNT(CASE WHEN orders.order_status = 'Cancelled' THEN 1 END) AS cancelled_orders, COUNT(*) AS total_orders,COUNT(CASE WHEN orders.order_status = 'Cancelled' THEN 1 END) * 100.0 / COUNT(*) AS cancellation_rate FROM restaurants INNER JOIN orders ON restaurants.restaurant_id = orders.restaurant_id GROUP BY restaurants.restaurant_name ORDER BY cancellation_rate DESC LIMIT 1;

